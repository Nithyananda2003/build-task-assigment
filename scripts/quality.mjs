import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {gzipSync} from 'node:zlib';
const read = path => readFileSync(path,'utf8');
assert.equal(read('README.md').split(/\r?\n/)[0],'Ref: KL-7Q4','README must start with the required reference');
const spec = JSON.parse(read('api.openapi.json'));
assert.equal(spec.openapi,'3.1.0');
assert.deepEqual(Object.keys(spec.paths),['/api/health','/api/state','/api/complete']);
const manifest = JSON.parse(read('.openai/hosting.json'));
assert.equal(manifest.d1,'DB');assert.ok(manifest.project_id);assert.equal(manifest.static,undefined);
const migration = read('drizzle/0000_daily_spark.sql');assert.match(migration,/PRIMARY KEY \(user_id, day\)/);assert.match(migration,/CHECK\(points = 10 \+ correct \* 5\)/);
const html=read('public/index.html');assert.match(html,/name="viewport"/);assert.match(html,/<html lang="en">/);
assert.ok(!/https?:\/\//.test(html),'HTML must not load any third-party resource');
const assets=['index.html','style.css','app.js','icon.svg','manifest.webmanifest','sw.js'];
const bytes=assets.reduce((sum,f)=>sum+Buffer.byteLength(read('public/'+f)),0);
const zipped=assets.reduce((sum,f)=>sum+gzipSync(read('public/'+f)).length,0);
assert.ok(zipped<25000,`Assets exceed the 25 kB gzip budget: ${zipped}`);
assert.ok(!read('public/app.js').includes('const WORDS'),'Answer keys must stay on the server');
assert.ok(!read('public/sw.js').includes("cache.put('/api"),'API responses must not be cached');
console.log(`Quality checks passed. ${bytes} asset bytes raw; ${zipped} bytes gzip in total. No dependencies or third-party assets.`);
